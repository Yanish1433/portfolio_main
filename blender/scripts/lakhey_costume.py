def normal_from_height(H, mpp_u, mpp_v):
    """Tangent-space normal map (OpenGL/glTF: +X = +u, +Y = +v) from a height field in metres."""
    mpp_v = np.asarray(mpp_v, dtype=np.float64)
    mpp_u = np.asarray(mpp_u, dtype=np.float64)
    if mpp_u.ndim == 1:
        mpp_u = mpp_u[:, None]
    gu = (np.roll(H, -1, 1) - np.roll(H, 1, 1)) / (2 * mpp_u)
    gv = (np.roll(H, -1, 0) - np.roll(H, 1, 0)) / (2 * mpp_v)
    n = np.stack([-gu, -gv, np.ones_like(H)], -1)
    n /= np.linalg.norm(n, axis=-1, keepdims=True)
    return n * 0.5 + 0.5


def uv_scale(obj):
    """Metres per UV unit (sqrt of 3D area / UV area)."""
    me = obj.data
    uv = me.uv_layers.active.data
    a3 = sum(p.area for p in me.polygons)
    a2 = 0.0
    for p in me.polygons:
        pts = [uv[i].uv for i in p.loop_indices]
        a2 += 0.5 * abs(sum(pts[i].x * pts[i - 1].y - pts[i - 1].x * pts[i].y for i in range(len(pts))))
    return math.sqrt(a3 / max(a2, 1e-9))


def robe_normal_map(size, r_top):
    us = (np.arange(size) + 0.5) / size
    U, V = np.meshgrid(us, us)
    f = np.clip(1 - V / 0.72, 0, 1)                         # skirt: hem at v=0
    rx, ry = skirt_radii(f, r_top)
    circ = 2 * np.pi * np.sqrt((rx ** 2 + ry ** 2) / 2)
    z_m = (Z_TOP - Z_HEM) * (V / 0.72)
    H = (0.0007 * f * np.sin(2 * np.pi * U * 46 + 2 * np.sin(z_m * 9))
         + 0.0002 * np.sin(2 * np.pi * U * 120 + 3 * np.sin(z_m * 17))
         + 0.0006 * (1 - f) ** 2 * np.sin(z_m * 60 + 2 * np.sin(U * 25)))
    H = np.where(V < 0.72, H, 0.0004 * np.sin(U * 700) * np.sin(V * 640))
    mpp_u = np.where(V < 0.72, circ, 1.0)[:, 0] / size
    return normal_from_height(H, mpp_u, (Z_TOP - Z_HEM) / (0.72 * size))


def tunic_maps(size, m_per_uv):
    """Saffron cloth with a subtle weave + large soft folds (normal), both in UV space."""
    us = (np.arange(size) + 0.5) / size
    U, V = np.meshgrid(us, us)
    x, y = U * m_per_uv, V * m_per_uv
    H = (0.0014 * np.sin(x * 48 + 2.2 * np.sin(y * 31)) * np.sin(y * 36 + 1.7 * np.sin(x * 27))
         + 0.0003 * np.sin(x * 120 + y * 70))
    weave = np.sign(np.sin(2 * np.pi * x / 0.005)) * np.sign(np.sin(2 * np.pi * y / 0.005))
    H += 0.00012 * weave
    nrm = normal_from_height(H, m_per_uv / size, m_per_uv / size)
    col = np.tile(TUNIC_YELLOW[None, None], (size, size, 1)) * (1 + 0.035 * weave + 0.03 * np.sin(x * 23) * np.sin(y * 17))[..., None]
    return np_image("Tunic_base", col, True), np_image("Tunic_normal", nrm, False)


def make_collar(tunic):
    """Red/gold trim ring at the tunic neckline (Robe atlas band v 0.724-0.736)."""
    co = C.get_co(tunic.data)
    ztop = co[:, 2].max()
    sel = co[:, 2] > ztop - 0.02
    c = (co[sel][:, :2].max(0) + co[sel][:, :2].min(0)) / 2
    r = (co[sel][:, :2].max(0) - co[sel][:, :2].min(0)) / 2
    a = np.linspace(0, 2 * np.pi, 28, endpoint=False)
    rows = []
    for dz, d in ((-0.030, 0.000), (-0.026, 0.006), (-0.014, 0.008), (-0.004, 0.006), (0.0, 0.000)):
        z = ztop - 0.012 + dz
        rows.append(np.stack([c[0] + np.sin(a) * (r[0] + 0.004 + d), c[1] - np.cos(a) * (r[1] + 0.004 + d),
                              np.full_like(a, z)], -1))
    ob = grid_obj("Collar", np.stack(rows, 0), closed_u=True, uv_rect=(0.0, 1.0, 0.724, 0.736))
    n = len(ob.data.vertices)
    set_weights(ob, {"Neck": np.full(n, 0.5), "Spine2": np.full(n, 0.5)})
    return ob


def bake_cloth(low, size, strength, tag, base_img=None, base_color=None, rough=0.7, sheen=0.0, normal_img=None):
    """Analytic UV-space normal map (no high-poly bake grid) + AO with the whole character as occluder."""
    low.data.materials.clear()
    low.data.materials.append(C.new_material(tag + "Bake"))
    nimg = normal_img
    ao = C.new_image(tag + "_ao", size, (1, 1, 1, 1), non_color=True)
    bpy.context.scene.world.light_settings.distance = 0.12
    C.bake(low, "AO", ao, samples=64, margin=8)
    px = C.img_pixels(ao).copy()
    px[..., :3] = 1 - 0.75 * (1 - px[..., :3])
    ao.pixels.foreach_set(px.ravel())
    orm = C.pack_orm(tag + "_orm", size, ao_img=ao, rough_const=rough)
    if base_img is None:
        base_img = np_image(tag + "_base", np.tile(np.asarray(base_color)[None, None], (8, 8, 1)), True)
    mat = C.final_pbr_material(tag, base_img, orm, nimg, normal_strength=1.0, sheen=sheen)
    mat.use_backface_culling = False
    low.data.materials.clear()
    low.data.materials.append(mat)
    bpy.data.images.remove(ao)
    return mat, (base_img, orm, nimg)


def robe_base_texture(size):
    """Red cloth with a gold trim near the skirt hem and on the cape edges (UV space paint)."""
    us = (np.arange(size) + 0.5) / size
    U, V = np.meshgrid(us, us)
    col = np.tile(ROBE_RED[None, None], (size, size, 1)).astype(np.float64)
    streak = 0.06 * np.sin(U * 2 * np.pi * 37 + 2 * np.sin(V * 9)) + 0.04 * np.sin(V * 400 + U * 30)
    col *= (1 + streak)[..., None]
    # skirt occupies v in [0, 0.72] with the hem at v=0 (top of the skirt at v=0.72)
    m = (V > 0.722) & (V < 0.738)                       # collar trim: gold with a red centre line
    col[m] = srgb(222, 160, 44)
    col[m & (np.abs(V - 0.730) < 0.0015)] = ROBE_RED
    for v0, w in ((0.020, 0.008), (0.036, 0.003)):
        m = (V < 0.72) & (np.abs(V - v0) < w)
        col[m] = srgb(222, 160, 44)
    # cape lower edges (v ~ 0.93 band end)
    m = (V > 0.80) & (V < 0.93) & (np.abs(V - 0.92) < 0.004)
    col[m] = srgb(222, 160, 44)
    return np_image("Robe_base", col, True)
