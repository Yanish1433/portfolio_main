"""Lakhey costume, hair and skin, built around the neutral MPFB body (T-pose rest).

Everything is generated by code: grid meshes (robe, sash, capes, apron, hair clumps) and offset
copies of the MPFB body (tunic). Each part gets skin weights for the shared mixamo rig.
Materials (glTF-safe, Principled + image textures only):
  Skin (factor), Tunic (ORM + normal), Robe (base + ORM + normal; skirt, sash, capes, wrist bands,
  sandals share one atlas), Hair (numpy strand textures), Metal (bells; shared with the mask gold).
"""
