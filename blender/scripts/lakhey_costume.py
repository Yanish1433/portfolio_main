RNG = np.random.default_rng(11)
srgb = LM.srgb
P = C.PREFIX

ROBE_RED = srgb(150, 14, 20)
TUNIC_YELLOW = srgb(232, 178, 30)            # #E8B21E
SKIN = srgb(176, 120, 92)
HAIR_RED = srgb(170, 22, 20)

TORSO_BONES = {"Hips", "Spine", "Spine1", "Spine2", "Neck", "LeftShoulder", "RightShoulder"}
UPPER_ARM = {"LeftArm", "RightArm"}
LOWER_ARM = {"LeftForeArm", "RightForeArm"}


# ------------------------------------------------------------------ helpers
def bone_head(arm, short):
    return np.array(arm.matrix_world @ C.pbone(arm, short).bone.head_local)


def bone_tail(arm, short):
    return np.array(arm.matrix_world @ C.pbone(arm, short).bone.tail_local)


def dominant(obj):
    """Per-vertex name (without prefix) of the strongest deform group."""
    gw = C.all_group_weights(obj)
    names = [n for n in gw if n.startswith(P)]
    W = np.stack([gw[n] for n in names], 1)
    idx = W.argmax(1)
    short = np.array([n[len(P):] for n in names])
    return short[idx], W.max(1)


def keep_vertices(obj, keep):
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    bm.verts.ensure_lookup_table()
    bmesh.ops.delete(bm, geom=[bm.verts[i] for i in np.nonzero(~keep)[0]], context="VERTS")
    bm.to_mesh(obj.data)
    bm.free()
    obj.data.update()


def decimate(obj, target_tris):
    tris = C.count_tris([obj])
    if tris > target_tris:
        mod = obj.modifiers.new("dec", "DECIMATE")
        mod.ratio = target_tris / tris
        mod.use_collapse_triangulate = True
        C.apply_modifier(obj, mod)
    return C.count_tris([obj])


def set_weights(obj, weights):
    """weights: dict short_bone -> per-vertex array; replaces existing groups."""
    obj.vertex_groups.clear()
    n = len(obj.data.vertices)
    tot = np.zeros(n)
    for w in weights.values():
        tot += w
    tot = np.maximum(tot, 1e-9)
    for short, w in weights.items():
        w = w / tot
        vg = obj.vertex_groups.new(name=P + short)
        for val in np.unique(np.round(w, 3)):
            if val <= 0.001:
                continue
            ids = np.nonzero(np.round(w, 3) == val)[0].tolist()
            vg.add(ids, float(val), "REPLACE")


def orient_grid(ob, G, ref=None):
    """Make face normals point away from `ref` (callable centre -> reference point), or away from
    each row's centroid for tubes (default)."""
    me = ob.data
    n = len(me.polygons)
    if n == 0:
        return
    cen = np.empty(n * 3)
    nor = np.empty(n * 3)
    me.polygons.foreach_get("center", cen)
    me.polygons.foreach_get("normal", nor)
    cen, nor = cen.reshape(-1, 3), nor.reshape(-1, 3)
    if ref is None:
        row_c = G.mean(axis=1)
        rows_idx = np.repeat(np.arange(G.shape[0] - 1), len(me.polygons) // (G.shape[0] - 1))
        refp = 0.5 * (row_c[rows_idx] + row_c[rows_idx + 1])
    else:
        refp = ref(cen)
    if np.sum(np.sum(nor * (cen - refp), axis=1)) < 0:
        me.flip_normals()
        me.update()


def grid_obj(name, G, closed_u=False, uv_rect=None, double_sided=False, ref=None):
    """Mesh from a (rows, cols, 3) grid with per-corner UVs mapped into uv_rect=(u0,u1,v0,v1)."""
    rows, cols = G.shape[:2]
    ob = LM.mesh_from_grid(name, G, closed_u=closed_u)
    orient_grid(ob, G, ref)
    if uv_rect is not None:
        u0, u1, v0, v1 = uv_rect
        cu = cols if closed_u else cols - 1
        uvs = []
        for j in range(rows - 1):
            for i in range(cu):
                for (ii, jj) in ((i, j), (i + 1, j), (i + 1, j + 1), (i, j + 1)):
                    uvs.append((u0 + (u1 - u0) * ii / cu, v0 + (v1 - v0) * jj / (rows - 1)))
        uv = ob.data.uv_layers.new(name="UVMap")
        uv.data.foreach_set("uv", np.array(uvs).ravel())
    return ob


def fit_uv_rect(obj, rect, margin=0.004):
    """Smart-UV an object and squeeze its islands into rect (keeps aspect)."""
    C.smart_uv(obj, margin=0.01)
    me = obj.data
    uv = me.uv_layers.active
    a = np.empty(len(me.loops) * 2)
    uv.data.foreach_get("uv", a)
    a = a.reshape(-1, 2)
    mn, mx = a.min(0), a.max(0)
    u0, u1, v0, v1 = rect
    sc = min((u1 - u0 - 2 * margin) / max(mx[0] - mn[0], 1e-6), (v1 - v0 - 2 * margin) / max(mx[1] - mn[1], 1e-6))
    a = (a - mn) * sc + np.array([u0 + margin, v0 + margin])
    uv.data.foreach_set("uv", a.ravel())


def cross_section(co, z, half=0.012, sel=None):
    m = np.abs(co[:, 2] - z) < half
    if sel is not None:
        m &= sel
    if not m.any():
        return None
    pts = co[m]
    cx, cy = (pts[:, 0].max() + pts[:, 0].min()) / 2, (pts[:, 1].max() + pts[:, 1].min()) / 2
    return np.array([cx, cy]), np.array([(pts[:, 0].max() - pts[:, 0].min()) / 2, (pts[:, 1].max() - pts[:, 1].min()) / 2])


# ------------------------------------------------------------------ body split
def split_body(body, arm):
    """Return (skin, tunic). Skin keeps forearms, hands, feet + ankles; tunic is the torso/upper-arm
    shell pushed outward. The rest of the body (hidden under robe/mask/hair) is deleted."""
    dom, _ = dominant(body)
    co = C.get_co(body.data)
    elbow_x = abs(bone_head(arm, "LeftForeArm")[0])
    is_hand = np.array(["Hand" in d for d in dom])
    keep_skin = np.isin(dom, list(LOWER_ARM)) | is_hand | np.isin(dom, ["LeftFoot", "RightFoot", "LeftToeBase", "RightToeBase"])
    keep_skin |= np.isin(dom, ["LeftLeg", "RightLeg"]) & (co[:, 2] < 0.20)
    # keep the forearm from a little above the elbow (hidden under the sleeve end)
    keep_skin |= np.isin(dom, list(UPPER_ARM)) & (np.abs(co[:, 0]) > elbow_x - 0.03)
    tunic_sel = (np.isin(dom, list(TORSO_BONES | UPPER_ARM)) & (co[:, 2] > 0.90))
    tunic_sel |= np.isin(dom, list(LOWER_ARM)) & (np.abs(co[:, 0]) < elbow_x + 0.06)
    tunic = C.duplicate(body, "Tunic")
    skin = body
    skin.name = skin.data.name = "Skin"
    keep_vertices(skin, keep_skin)
    keep_vertices(tunic, tunic_sel)
    # push the tunic out along the normals: looser on the torso, flared towards the sleeve ends
    me = tunic.data
    me.update()
    co = C.get_co(me)
    nrm = C.get_normals(me)
    ax = np.abs(co[:, 0])
    sleeve = C.smoothstep(0.16, 0.22, ax)
    flare = C.smoothstep(elbow_x - 0.12, elbow_x + 0.06, ax)
    off = 0.016 * (1 - sleeve) + (0.013 + 0.028 * flare) * sleeve
    co = co + nrm * off[:, None]
    edges = C.get_edges(me)
    co = C.smooth_weighted(co, edges, np.full(len(co), 0.7), iterations=28)
    C.set_co(me, co)
    # smooth the copied skin weights (numpy, along mesh edges) so the shell bends without crumpling
    gw = {k[len(P):]: v for k, v in C.all_group_weights(tunic).items() if k.startswith(P)}
    gw = {k: C.smooth_scalar(v, edges, 10) for k, v in gw.items() if v.max() > 0.01}
    set_weights(tunic, gw)
    return skin, tunic


# ------------------------------------------------------------------ robe (skirt) + sash + apron + bells
Z_TOP, Z_HEM = 1.00, 0.115


def skirt_frame(body_co):
    sec = cross_section(body_co, Z_TOP, 0.02, body_co[:, 2] > 0)
    c, r = sec
    return c, r


HEM_RX, HEM_RY, FLARE = 0.43, 0.36, 1.6


def skirt_radii(f, r_top):
    return (r_top[0] + 0.035 + (HEM_RX - r_top[0]) * f ** FLARE,
            r_top[1] + 0.035 + (HEM_RY - r_top[1]) * f ** FLARE)


def skirt_points(c_top, r_top, n_around=56, n_rows=16, folds=15):
    a = np.linspace(0, 2 * np.pi, n_around, endpoint=False)          # 0 = front (-Y)
    rows = []
    jitter = RNG.normal(0, 0.35, folds)
    for j in range(n_rows):
        f = j / (n_rows - 1)                                           # 0 top -> 1 hem
        z = Z_TOP + (Z_HEM - Z_TOP) * f
        rx, ry = skirt_radii(f, r_top)
        amp = 0.003 + 0.038 * f ** 1.2
        ph = a * folds + np.interp(a, np.linspace(0, 2 * np.pi, folds + 1), np.append(jitter, jitter[0])) * 2.0
        wave = np.sin(ph)
        wave = np.sign(wave) * np.abs(wave) ** 0.65                     # sharper ridges, rounder valleys
        rr = 1.0 + (amp * wave) / max(rx, ry)
        x = np.sin(a) * rx * rr
        y = c_top[1] - np.cos(a) * ry * rr
        zz = np.full_like(a, z) + (0.028 * f ** 3) * np.sin(ph + 0.6) + 0.012 * f ** 3 * np.sin(2 * a + 1.0)
        rows.append(np.stack([x, y, zz], -1))
    return np.stack(rows, 0)


def skirt_weights(co, top=Z_TOP, hem=Z_HEM):
    f = np.clip((top - co[:, 2]) / (top - hem), 0, 1)
    x = co[:, 0]
    sideL = C.smoothstep(-0.05, 0.10, x)
    sideR = C.smoothstep(0.05, -0.10, x)
    up = 0.30 * C.smoothstep(0.05, 0.55, f)
    low = 0.22 * C.smoothstep(0.45, 1.0, f)
    w = {"LeftUpLeg": up * sideL, "RightUpLeg": up * sideR, "LeftLeg": low * sideL, "RightLeg": low * sideR}
    legs = sum(w.values())
    w["Hips"] = np.maximum(1.0 - legs, 0.4)
    return w


def make_skirt(body_co):
    c, r = skirt_frame(body_co)
    G = skirt_points(c, r)
    ob = grid_obj("Skirt", G, closed_u=True, uv_rect=(0.0, 1.0, 0.72, 0.0))
    set_weights(ob, skirt_weights(C.get_co(ob.data)))
    return ob, c, r


def make_sash(c, r):
    a = np.linspace(0, 2 * np.pi, 40, endpoint=False)
    prof = [(0.915, 0.036), (0.93, 0.048), (0.975, 0.054), (1.02, 0.052), (1.055, 0.042), (1.07, 0.030)]
    rows = []
    for z, d in prof:
        rows.append(np.stack([np.sin(a) * (r[0] + d), c[1] - np.cos(a) * (r[1] + d), np.full_like(a, z)], -1))
    ob = grid_obj("Sash", np.stack(rows, 0), closed_u=True, uv_rect=(0.0, 1.0, 0.74, 0.79))
    co = C.get_co(ob.data)
    set_weights(ob, {"Hips": np.full(len(co), 0.7), "Spine": np.full(len(co), 0.3)})
    return ob


def make_bells(c, r, metal_mat):
    bells = []
    angs = np.radians(np.linspace(-115, 115, 13))
    for k, a in enumerate(angs):
        z = 0.905 + 0.006 * math.cos(3 * a)
        pos = Vector((math.sin(a) * (r[0] + 0.064), c[1] - math.cos(a) * (r[1] + 0.064), z))
        bm = bmesh.new()
        bmesh.ops.create_uvsphere(bm, u_segments=10, v_segments=6, radius=0.019)
        for v in bm.verts:                       # ghunguru bell: slightly pinched lower half
            if v.co.z < -0.006:
                v.co.x *= 0.92
                v.co.y *= 0.92
        sphere = LM.bm_to_obj(bm, f"Bell{k}")
        ring = LM.bm_to_obj(LM.make_torus_bm(0.006, 0.0018, 8, 4), f"BellLoop{k}")
        ring.rotation_euler = (0.0, math.pi / 2, 0.0)
        ring.location = (0, 0, 0.021)
        C.apply_transform(ring)
        ob = C.join_objects([sphere, ring], f"Bell{k}")
        ob.location = pos
        C.apply_transform(ob)
        bells.append(ob)
    ob = C.join_objects(bells, "Bells")
    ob.data.materials.append(metal_mat)
    set_weights(ob, {"Hips": np.ones(len(ob.data.vertices))})
    return ob


def make_apron(c, r):
    """Yellow front panel hanging from the sash over the skirt (tunic hem)."""
    rows = []
    zs = np.linspace(0.925, 0.64, 8)
    for j, z in enumerate(zs):
        f = (Z_TOP - z) / (Z_TOP - Z_HEM)
        rx, ry = skirt_radii(f, r)
        half = math.radians(30 + 10 * j / 7)
        a = np.linspace(-half, half, 11)
        fold = 0.010 * (j / 7) * np.sin(a * 9 + 0.5)
        x = np.sin(a) * (rx + 0.020 + fold)
        y = c[1] - np.cos(a) * (ry + 0.020 + fold) - 0.012 * (j / 7)
        zz = np.full_like(a, z) - 0.02 * (j / 7) * np.cos(a * 4) ** 2
        rows.append(np.stack([x, y, zz], -1))
    ob = grid_obj("Apron", np.stack(rows, 0), uv_rect=(0.0, 1.0, 0.0, 0.14),
                  ref=lambda cen: np.stack([np.zeros(len(cen)), np.full(len(cen), c[1]), cen[:, 2]], 1))
    set_weights(ob, skirt_weights(C.get_co(ob.data)))
    return ob


# ------------------------------------------------------------------ capes, wrist bands, sandals
def make_capes(arm):
    capes = []
    for side, sx in (("Left", 1), ("Right", -1)):
        sh = bone_head(arm, side + "Arm")
        el = bone_head(arm, side + "ForeArm")
        rows = []
        ds = np.linspace(-0.07, 0.17, 12)
        for d in ds:
            f = (d + 0.07) / 0.24
            ctr = sh + np.array([sx * d, 0.0, 0.004])
            rad = 0.080 + 0.050 * f ** 1.3
            b = np.radians(np.linspace(-125, 125, 11))         # around the arm axis, 0 = top
            drape = 0.020 * f * np.abs(np.sin(b)) ** 2
            y = ctr[1] + np.sin(b) * rad
            z = ctr[2] + np.cos(b) * rad - drape
            ripple = 0.006 * f * np.sin(b * 6 + d * 30)
            x = np.full_like(b, ctr[0]) + sx * ripple
            rows.append(np.stack([x, y, z], -1))
        G = np.stack(rows, 0)
        ob = grid_obj(f"Cape{side}", G, uv_rect=(0.0 if sx > 0 else 0.5, 0.5 if sx > 0 else 1.0, 0.80, 0.93))
        co = C.get_co(ob.data)
        d = (co[:, 0] - sh[0]) * sx
        wa = C.smoothstep(-0.02, 0.10, d)
        set_weights(ob, {side + "Shoulder": (1 - wa) * 0.7, "Spine2": (1 - wa) * 0.3, side + "Arm": wa})
        capes.append(ob)
    return capes


def make_wristbands(arm, skin):
    out = []
    co = C.get_co(skin.data)
    for i, (side, sx) in enumerate((("Left", 1), ("Right", -1))):
        wr = bone_head(arm, side + "Hand")
        x0 = wr[0] - sx * 0.025
        m = (np.abs(co[:, 0] - x0) < 0.008) & (np.sign(co[:, 0]) == sx)
        yz = co[m][:, 1:]
        cyz = (yz.max(0) + yz.min(0)) / 2
        ry, rz = (yz.max(0) - yz.min(0)) / 2 + 0.006
        a = np.linspace(0, 2 * np.pi, 18, endpoint=False)
        rows = []
        for dx, grow in ((-0.020, 0.0), (-0.016, 0.004), (0.0, 0.006), (0.016, 0.004), (0.020, 0.0)):
            rows.append(np.stack([np.full_like(a, x0 + dx), cyz[0] + np.cos(a) * (ry + grow), cyz[1] + np.sin(a) * (rz + grow)], -1))
        ob = grid_obj(f"WristBand{side}", np.stack(rows, 0), closed_u=True,
                      uv_rect=(0.25 * i, 0.25 * i + 0.25, 0.94, 1.0))
        set_weights(ob, {side + "ForeArm": np.ones(len(ob.data.vertices))})
        out.append(ob)
    return out


def make_sandals(arm, skin):
    out = []
    co = C.get_co(skin.data)
    for i, (side, sx) in enumerate((("Left", 1), ("Right", -1))):
        m = (np.sign(co[:, 0]) == sx) & (co[:, 2] < 0.035)
        fp = co[m]
        x0, x1 = fp[:, 0].min(), fp[:, 0].max()
        y0, y1 = fp[:, 1].min(), fp[:, 1].max()
        sole = LM.make_rounded_box(((x1 - x0) + 0.016, (y1 - y0) + 0.02, 0.014), 0.006, 2)
        sob = LM.bm_to_obj(sole, f"Sole{side}")
        sob.location = ((x0 + x1) / 2, (y0 + y1) / 2 - 0.002, 0.004)
        C.apply_transform(sob)
        # instep strap: an arch over the foot at 40% from the heel
        ys = y1 - 0.42 * (y1 - y0)
        mm = (np.sign(co[:, 0]) == sx) & (np.abs(co[:, 1] - ys) < 0.01) & (co[:, 2] < 0.12)
        sec = co[mm]
        cx = (sec[:, 0].max() + sec[:, 0].min()) / 2
        hw = (sec[:, 0].max() - sec[:, 0].min()) / 2 + 0.006
        top = sec[:, 2].max() + 0.005
        b = np.linspace(-math.pi / 2, math.pi / 2, 12)
        rows = []
        for dy, th in ((-0.012, 0.0), (-0.010, 0.003), (0.010, 0.003), (0.012, 0.0)):
            rows.append(np.stack([cx + np.sin(b) * hw, np.full_like(b, ys + dy),
                                  0.008 + (top - 0.008) * np.cos(b) ** 0.7 + th], -1))
        strap = grid_obj(f"Strap{side}", np.stack(rows, 0))
        sandal = C.join_objects([sob, strap], f"Sandal{side}")
        fit_uv_rect(sandal, (0.5 + 0.25 * i, 0.75 + 0.25 * i, 0.94, 1.0))
        sc = C.get_co(sandal.data)
        toe = C.smoothstep(y0 + 0.30 * (y1 - y0), y0 + 0.20 * (y1 - y0), sc[:, 1])   # -Y is front
        set_weights(sandal, {side + "Foot": 1 - toe, side + "ToeBase": toe})
        out.append(sandal)
    return out


# ------------------------------------------------------------------ hair
def hair_textures(size=512):
    """Tileable strand textures: base colour, tangent normal, ORM (AO darker at the roots)."""
    u = np.arange(size) / size
    h = np.zeros(size)
    for k in range(40):
        f = RNG.integers(8, 90)
        h += RNG.uniform(0.2, 1.0) / f ** 0.5 * np.sin(2 * np.pi * f * u + RNG.uniform(0, 6.28))
    h = (h - h.min()) / np.ptp(h)
    v = (np.arange(size) / size)[:, None]
    H = np.tile(h[None, :], (size, 1))
    base = HAIR_RED[None, None, :] * (0.55 + 0.75 * H[..., None])
    base *= (0.55 + 0.45 * C.smoothstep(0.0, 0.25, v))[..., None]            # darker roots
    base = np.clip(base + 0.05 * C.smoothstep(0.7, 1.0, v)[..., None] * srgb(255, 140, 90), 0, 1)
    dh = np.gradient(H, axis=1) * size / 30.0
    nrm = np.stack([0.5 - 0.5 * np.clip(dh, -1, 1), np.full_like(H, 0.5), np.ones_like(H)], -1)
    ao = (0.55 + 0.45 * C.smoothstep(0.0, 0.3, v)) * (0.75 + 0.25 * H)
    orm = np.stack([ao, 0.42 + 0.25 * (1 - H), np.zeros_like(H)], -1)
    return base, nrm, orm


def np_image(name, arr, srgb_space):
    size = arr.shape[0]
    img = bpy.data.images.new(name, arr.shape[1], size, alpha=False)
    px = np.ones((size, arr.shape[1], 4), dtype=np.float32)
    a = np.clip(arr, 0, 1)
    if srgb_space:
        a = np.where(a <= 0.0031308, a * 12.92, 1.055 * np.power(a, 1 / 2.4) - 0.055)
        img.colorspace_settings.name = "sRGB"
    else:
        img.colorspace_settings.name = "Non-Color"
    px[..., :3] = a
    img.pixels.foreach_set(px.ravel())
    return img


class Collider:
    def __init__(self, objs):
        verts, polys, off = [], [], 0
        dg = bpy.context.evaluated_depsgraph_get()
        for o in objs:
            me = o.evaluated_get(dg).to_mesh()
            mw = o.matrix_world
            verts += [mw @ v.co for v in me.vertices]
            polys += [[i + off for i in p.vertices] for p in me.polygons]
            off += len(me.vertices)
            o.evaluated_get(dg).to_mesh_clear()
        self.tree = BVHTree.FromPolygons(verts, polys)

    def push_out(self, p, clearance):
        loc, nrm, _i, dist = self.tree.find_nearest(Vector(p))
        if loc is None:
            return p
        d = Vector(p) - loc
        if d.dot(nrm) < clearance:
            return np.array(loc + nrm * clearance)
        return p


def clump(root, out_dir, length, r0, steps=8, sides=5, wiggle=0.012, gravity=0.55, collider=None, up=False,
          shell=None):
    """Tapered, slightly flattened hair clump falling from root. Returns a (rows, sides, 3) grid.
    shell=(centre, radii): keep the path outside this ellipsoid (the hair cap)."""
    pts = [np.array(root)]
    d = np.array(out_dir) / np.linalg.norm(out_dir)
    step = length / steps
    ph = RNG.uniform(0, 6.28)
    side_vec = np.cross(d, [0, 0, 1.0])
    if np.linalg.norm(side_vec) < 1e-6:
        side_vec = np.array([1.0, 0, 0])
    side_vec /= np.linalg.norm(side_vec)
    for i in range(steps):
        d = d + np.array([0, 0, -gravity]) * (1.0 / steps) * 3.0
        d /= np.linalg.norm(d)
        q = pts[-1] + d * step + side_vec * wiggle * math.sin(ph + i * 1.3) * (i / steps)
        if shell is not None:
            sc, sr = shell
            k = np.linalg.norm((q - sc) / sr)
            if k < 1.0:
                q = sc + (q - sc) / k
        if collider is not None:
            q = collider.push_out(q, 0.016 + 0.006 * (i / steps))
        dn = (q - pts[-1]) / max(np.linalg.norm(q - pts[-1]), 1e-9)
        d = 0.5 * d + 0.5 * dn
        d /= np.linalg.norm(d)
        pts.append(q)
    pts = np.array(pts)
    rows = []
    a = np.linspace(0, 2 * np.pi, sides, endpoint=False)
    for i, p in enumerate(pts):
        f = i / steps
        t = pts[min(i + 1, steps)] - pts[max(i - 1, 0)]
        t /= np.linalg.norm(t)
        x = np.cross(t, [0, 0, 1.0]) if abs(t[2]) < 0.95 else np.cross(t, [1.0, 0, 0])
        x /= np.linalg.norm(x)
        y = np.cross(t, x)
        r = r0 * (1 - 0.88 * f ** 1.2)
        rows.append(p + (np.cos(a)[:, None] * x * r * 1.25 + np.sin(a)[:, None] * y * r * 0.70))
    return np.stack(rows, 0)


def make_hair(collider):
    """Hair cap behind/over the mask + ~38 chunky clumps + topknot tuft above the third eye."""
    c = np.array([0.0, LM.CY + 0.022, LM.Z0 - 0.005])
    R = np.array([0.150, 0.150, 0.185])

    def cap_pt(theta, phi, extra=0.0):
        cp = math.cos(phi)
        d = np.array([cp * math.sin(theta), -cp * math.cos(theta), math.sin(phi)])
        return c + d * (R + extra), d

    # cap: covers the back and the top behind the mask edge
    th = np.radians(np.linspace(80, 280, 22))
    ph = np.radians(np.linspace(-55, 88, 12))
    G = np.array([[cap_pt(t, p)[0] for t in th] for p in ph])
    cap = grid_obj("HairCap", G, uv_rect=(0.0, 3.0, 0.0, 0.25))
    pieces = [cap]
    roots = []
    # frame ring just behind the mask edge (falls in front of the shoulders), back rows, crown
    for side in (1, -1):
        for p in np.radians(np.linspace(-30, 66, 10)):
            roots.append((side * math.radians(97), p, 0.44 + 0.14 * RNG.random(), 0.036))
    for t in np.radians(np.linspace(116, 244, 8)):
        for p in np.radians([-22, 14, 48]):
            roots.append((t + RNG.normal(0, 0.05), p, 0.46 + 0.14 * RNG.random(), 0.036))
    for t in np.radians(np.linspace(-70, 70, 5)):
        roots.append((math.pi + t, math.radians(74), 0.44 + 0.10 * RNG.random(), 0.034))
    shell = (c, R * 1.03)
    for k, (t, p, L, r0) in enumerate(roots):
        root, d = cap_pt(t, p, -0.006)
        down = np.array([0, 0, -1.0])
        tang = down - d * np.dot(down, d)                # slide down the scalp first, then fall
        tang /= max(np.linalg.norm(tang), 1e-6)
        out = tang + d * 0.45
        Gc = clump(root, out, L, r0 * RNG.uniform(0.85, 1.15), collider=collider, gravity=1.1, wiggle=0.022,
                   shell=shell)
        u0 = RNG.uniform(0, 3)
        pieces.append(grid_obj(f"Clump{k}", Gc, closed_u=True, uv_rect=(u0, u0 + 0.6, 0.0, 1.0)))
    # topknot: a red tuft rising above the third eye, curling back
    tp, tn = LM.surface_frame(0.0, 0.168)
    tp, tn = np.array(tp), np.array(tn)
    for k in range(7):
        a = (k - 3) * 0.32
        root = tp + np.array([0.010 * (k - 3), 0.004 * abs(k - 3), -0.002])
        out = tn * 0.5 + np.array([math.sin(a) * 0.5, 0.15, 1.0])
        Gc = clump(root, out, 0.085 + 0.03 * RNG.random(), 0.016, steps=5, sides=5, gravity=0.0, up=False,
                   wiggle=0.006)
        u0 = RNG.uniform(0, 3)
        pieces.append(grid_obj(f"Tuft{k}", Gc, closed_u=True, uv_rect=(u0, u0 + 0.5, 0.0, 1.0)))
    hair = C.join_objects(pieces, "Hair")
    co = C.get_co(hair.data)
    below = C.smoothstep(1.52, 1.25, co[:, 2])
    set_weights(hair, {"Head": 1.0 - 0.75 * below, "Neck": 0.35 * below, "Spine2": 0.40 * below})
    return hair


